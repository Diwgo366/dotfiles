#!/usr/bin/env bash
# Tema de colores para Midnight Commander

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/../common.sh"

main() {
    validate_colors_json
    extract_colors
    
    echo "▶ Instalando tema Midnight Commander..."
    
    MC_SKINS_DIR="/usr/share/mc/skins"

    # Verificar si tenemos permisos de escritura
    if [[ ! -w "$MC_SKINS_DIR" ]]; then
        echo "✗ Sin permisos en $MC_SKINS_DIR"
        echo "Ejecuta con sudo:"
        echo "  sudo $0"
        exit 1
    fi
    
    mkdir -p "$MC_SKINS_DIR"
    
    # Generar tema con Python
    python3 << 'PYEOF'
import json, os, sys

MC_SKINS_DIR = "/usr/share/mc/skins"

try:
    with open(os.environ['COLORS_JSON']) as f:
        d = json.load(f)
    
    a = d["ansi"]
    name = d.get("name", "custom_dotfiles")
    
    # Mapear colores hex a nombres de colores MC
    def hex_to_mc_color(hex_val):
        """Convierte un color hex a nombre de color de MC"""
        hex_val = hex_val.lstrip('#').lower()
        
        # Mapeo de colores ANSI a nombres de MC
        color_map = {
            a["color0"].lstrip('#').lower():  "black",
            a["color1"].lstrip('#').lower():  "red",
            a["color2"].lstrip('#').lower():  "green",
            a["color3"].lstrip('#').lower():  "yellow",
            a["color4"].lstrip('#').lower():  "blue",
            a["color5"].lstrip('#').lower():  "magenta",
            a["color6"].lstrip('#').lower():  "cyan",
            a["color7"].lstrip('#').lower():  "white",
            a["color8"].lstrip('#').lower():  "gray",
            a["color9"].lstrip('#').lower():  "brightred",
            a["color10"].lstrip('#').lower(): "brightgreen",
            a["color11"].lstrip('#').lower(): "brightyellow",
            a["color12"].lstrip('#').lower(): "brightblue",
            a["color13"].lstrip('#').lower(): "brightmagenta",
            a["color14"].lstrip('#').lower(): "brightcyan",
            a["color15"].lstrip('#').lower(): "white",
        }
        
        return color_map.get(hex_val, "white")
    
    # Generar contenido del tema
    mc_theme = f"""#
# {name} - Generated by colors/themes/mc.sh
# Auto-generated Midnight Commander skin
#

[skin]
    description = {name}
    256colors = false

[core]
    _default_ = white;default
    selected = black;{hex_to_mc_color(a["color14"])}
    marked = white;{hex_to_mc_color(a["color12"])}
    markselect = black;{hex_to_mc_color(a["color14"])};;bold
    gauge = white;{hex_to_mc_color(a["color4"])}
    input = white;black
    inputmark = white;{hex_to_mc_color(a["color12"])};bold
    inputunchanged = {hex_to_mc_color(a["color4"])};white
    commandlinemark = white;{hex_to_mc_color(a["color12"])};bold
    reverse = white;{hex_to_mc_color(a["color12"])}
    header = white;black
    disabled = gray;lightgray
    errors = white;{hex_to_mc_color(a["color1"])}

[menu]
    _default_ = white;default
    menusel = white;{hex_to_mc_color(a["color4"])};bold
    menuhot = white;default
    menuhotsel = white;black
    menuinactive = white

[dialog]
    _default_ = white;{hex_to_mc_color(a["color4"])}
    dhotnormal = black
    dfocus = {hex_to_mc_color(a["color4"])};white;bold
    dhotfocus = {hex_to_mc_color(a["color4"])};white
    dtitle = white;;bold

[popupmenu]
    _default_ = white;{hex_to_mc_color(a["color4"])}
    menusel = {hex_to_mc_color(a["color4"])};white;bold
    menutitle = white;;bold

[error]
    _default_ = white;{hex_to_mc_color(a["color1"])}
    errdfocus = {hex_to_mc_color(a["color1"])};white;bold
    errdhotnormal = black
    errdhotfocus = {hex_to_mc_color(a["color1"])};white
    errdtitle = white

[filehighlight]
    directory = {hex_to_mc_color(a["color4"])};bold
    executable = gray
    symlink = {hex_to_mc_color(a["color14"])}
    hardlink = {hex_to_mc_color(a["color14"])}
    stalelink = {hex_to_mc_color(a["color14"])}
    device = {hex_to_mc_color(a["color1"])}
    special = {hex_to_mc_color(a["color1"])}
    core = {hex_to_mc_color(a["color1"])}
    temp = {hex_to_mc_color(a["color5"])}
    archive = {hex_to_mc_color(a["color14"])}
    doc = white
    source = white
    media = white
    graph = gray
    database = {hex_to_mc_color(a["color1"])}

[buttonbar]
    button = white;{hex_to_mc_color(a["color4"])}
    hotkey = {hex_to_mc_color(a["color12"])};bold

[statusbar]
    _default_ = black;white

[help]
    _default_ = white;black
    helpitalic = white;;italic
    helpbold = {hex_to_mc_color(a["color12"])};bold
    helplink = {hex_to_mc_color(a["color4"])};underline
    helpslink = {hex_to_mc_color(a["color4"])};underline;bold
    helptitle = white;;bold

[editor]
    _default_ = white;black
    editbold = white;;bold
    editmarked = white;{hex_to_mc_color(a["color4"])};bold
    editwhitespace = white;{hex_to_mc_color(a["color4"])}
    editlinestate = black;white

[viewer]
    _default_ = white;black
    viewbold = ;;bold
    viewunderline = ;;underline
    viewselected = white;{hex_to_mc_color(a["color4"])};bold

[diffviewer]
    changedline = white;{hex_to_mc_color(a["color12"])}
    changednew = white;{hex_to_mc_color(a["color12"])}
    changed = white;{hex_to_mc_color(a["color1"])}
    added = {hex_to_mc_color(a["color2"])};{hex_to_mc_color(a["color2"])}
    removed = black;{hex_to_mc_color(a["color1"])}
    error = white;{hex_to_mc_color(a["color1"])}

[Lines]
    horiz = ─
    vert = │
    lefttop = ┌
    righttop = ┐
    leftbottom = └
    rightbottom = ┘
    topmiddle = ┬
    bottommiddle = ┴
    leftmiddle = ├
    rightmiddle = ┤
    cross = ┼
    dhoriz = ─
    dvert = │
    dlefttop = ┌
    drighttop = ┐
    dleftbottom = └
    drightbottom = ┘
    dtopmiddle = ─
    dbottommiddle = ─
    dleftmiddle = ├
    drightmiddle = ┤
"""
    
    # Escribir el archivo
    theme_file = os.path.join(MC_SKINS_DIR, f"{name}.ini")
    with open(theme_file, "w") as f:
        f.write(mc_theme)
    print(f"✓ Tema MC instalado en {theme_file}")
    
except Exception as e:
    print(f"✗ Error: {e}", file=sys.stderr)
    sys.exit(1)
PYEOF
}

main "$@"

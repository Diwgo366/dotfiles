#!/usr/bin/env lua
-- Genera hyprland-gui.lua desde colors.json
-- Uso: lua generate-hyprland.lua > ~/.config/hypr/hyprland-gui.lua

local json = require("dkjson")
local colors_json = arg[1] or os.getenv("HOME") .. "/Dotfiles/scripts/colors/colors.json"

local function read_json(path)
    local f = io.open(path, "r")
    if not f then
        error("No se pudo leer: " .. path)
    end
    local content = f:read("*a")
    f:close()
    local data, err = json.decode(content)
    if not data then
        error("JSON inválido: " .. err)
    end
    return data
end

local c = read_json(colors_json)
local s = c.structural
local p = c.palette

-- Conversión hex -> formato Hyprland (0xRRGGBB o 0xAARRGGBB)
local function hex_to_hypr(hex, alpha)
    hex = hex:gsub("#", "")
    if alpha then
        return string.format("0x%02x%s", alpha * 255, hex:upper())
    end
    return "0x" .. hex:upper()
end

-- Configuración base (valores por defecto, se pueden sobrescribir via env vars)
local rounding = tonumber(os.getenv("HYPR_ROUNDING")) or 10
local gaps_out = tonumber(os.getenv("HYPR_GAPS_OUT")) or 10
local border_size = tonumber(os.getenv("HYPR_BORDER_SIZE")) or 2
local active_opacity = tonumber(os.getenv("HYPR_ACTIVE_OPACITY")) or 0.9
local inactive_opacity = tonumber(os.getenv("HYPR_INACTIVE_OPACITY")) or 0.9
local blur_enabled = os.getenv("HYPR_BLUR_ENABLED") == "true"
local shadow_enabled = os.getenv("HYPR_SHADOW_ENABLED") == "true"

-- Colores principales
local active_border = hex_to_hypr(s.foreground)           -- #f8f8f2
local inactive_border = hex_to_hypr(p.color8)             -- #7A7A7A
local bg_color = hex_to_hypr(s.background, 0.93)          -- #282a36 con alpha ~EE
local shadow_color = hex_to_hypr("1a1a1a", 0.93)          -- negro suave

local out = {}

table.insert(out, "-- Generated by generate-hyprland.lua from colors.json")
table.insert(out, "-- Palette: " .. (c.name or "custom_dotfiles"))
table.insert(out, "")
table.insert(out, "-- Environment")
table.insert(out, 'hl.env("XCURSOR_THEME", "Future-cyan-cursors")')
table.insert(out, 'hl.env("XCURSOR_SIZE", "24")')
table.insert(out, "")
table.insert(out, "-- Settings")
table.insert(out, "hl.config({")
table.insert(out, "    animations = {")
table.insert(out, "        enabled = true,")
table.insert(out, "    },")
table.insert(out, "    decoration = {")
table.insert(out, string.format("        active_opacity = %.1f,", active_opacity))
table.insert(out, "        blur = {")
table.insert(out, "            contrast = 0.9,")
table.insert(out, string.format("            enabled = %s,", blur_enabled and "true" or "false"))
table.insert(out, "            ignore_opacity = false,")
table.insert(out, "            new_optimizations = true,")
table.insert(out, "            noise = 0.015,")
table.insert(out, "            passes = 1,")
table.insert(out, "            size = 1,")
table.insert(out, "            vibrancy = 0.1,")
table.insert(out, "        },")
table.insert(out, string.format("        inactive_opacity = %.1f,", inactive_opacity))
table.insert(out, string.format("        rounding = %d,", rounding))
table.insert(out, "        shadow = {")
table.insert(out, string.format("            color = \"%s\",", shadow_color))
table.insert(out, string.format("            color_inactive = \"%s\",", shadow_color))
table.insert(out, string.format("            enabled = %s,", shadow_enabled and "true" or "false"))
table.insert(out, "            range = 3,")
table.insert(out, "            render_power = 2,")
table.insert(out, "        },")
table.insert(out, "    },")
table.insert(out, "    general = {")
table.insert(out, string.format("        border_size = %d,", border_size))
table.insert(out, "        col = {")
table.insert(out, string.format("            active_border = \"%s\",", active_border))
table.insert(out, string.format("            inactive_border = \"%s\",", inactive_border))
table.insert(out, "        },")
table.insert(out, string.format("        gaps_out = %d,", gaps_out))
table.insert(out, "        layout = \"master\",")
table.insert(out, "    },")
table.insert(out, "    input = {")
table.insert(out, "        sensitivity = 1.0,")
table.insert(out, "    },")
table.insert(out, "    master = {")
table.insert(out, "        mfact = 0.5,")
table.insert(out, "        new_status = \"slave\",")
table.insert(out, "    },")
table.insert(out, "})")
table.insert(out, "")

-- Animations (se mantienen igual)
local anims = {
    {leaf = "global", enabled = false},
    {leaf = "windowsIn", enabled = true, speed = 8.0, bezier = "default", style = "popin"},
    {leaf = "windowsOut", enabled = true, speed = 8.0, bezier = "default", style = "popin"},
    {leaf = "windowsMove", enabled = true, speed = 8.0, bezier = "default"},
    {leaf = "layersIn", enabled = true, speed = 8.0, bezier = "default", style = "slide top"},
    {leaf = "layersOut", enabled = true, speed = 8.0, bezier = "default", style = "slide top"},
    {leaf = "fade", enabled = true, speed = 1.0, bezier = "default"},
    {leaf = "fadeIn", enabled = true, speed = 8.0, bezier = "default"},
    {leaf = "fadeOut", enabled = true, speed = 8.0, bezier = "default"},
    {leaf = "fadeLayersIn", enabled = true, speed = 8.0, bezier = "default"},
    {leaf = "fadeLayersOut", enabled = true, speed = 8.0, bezier = "default"},
    {leaf = "border", enabled = true, speed = 10.0, bezier = "default"},
    {leaf = "borderangle", enabled = true, speed = 1.0, bezier = "default"},
    {leaf = "workspaces", enabled = true, speed = 6.0, bezier = "default", style = "slide"},
    {leaf = "zoomFactor", enabled = false},
    {leaf = "monitorAdded", enabled = true, speed = 1.0, bezier = "default"},
}

table.insert(out, "-- Animations")
for _, a in ipairs(anims) do
    table.insert(out, "hl.animation({")
    table.insert(out, string.format("    leaf = \"%s\",", a.leaf))
    table.insert(out, string.format("    enabled = %s,", a.enabled and "true" or "false"))
    if a.speed then table.insert(out, string.format("    speed = %.1f,", a.speed)) end
    if a.bezier then table.insert(out, string.format("    bezier = \"%s\",", a.bezier)) end
    if a.style then table.insert(out, string.format("    style = \"%s\",", a.style)) end
    table.insert(out, "})")
end
table.insert(out, "")

-- Window rules (se mantienen igual)
local window_rules = {
    {class = "^(wofi)$", stay_focused = true},
    {class = "^(wofi)$", suppress_event = "change_focused"},
    {class = "^$", no_blur = true},
    {class = "^(xdg\\-desktop\\-portal\\-gtk|xarchiver)$", center = true, float = true, size = "[700, 500]"},
    {class = "^(Zotero|file\\-png)$", center = true, size = "700 500"},
    {title = "^(Pantalla\\ en\\ pantalla)$", opaque = true},
    {class = "^(google\\-chrome)$", opaque = true},
    {class = "^(org\\.gnome\\.gThumb)$", opaque = true},
    {title = "^(Imagen\\ en\\ imagen)$", opaque = true},
    {class = "^(brave\\-origin)$", opaque = true},
}

table.insert(out, "-- Window rules")
for _, r in ipairs(window_rules) do
    table.insert(out, "hl.window_rule({")
    table.insert(out, "    match = {")
    for k, v in pairs(r) do
        if k ~= "match" then
            -- handled below
        end
    end
    if r.class then table.insert(out, string.format("        class = \"%s\",", r.class)) end
    if r.title then table.insert(out, string.format("        title = \"%s\",", r.title)) end
    table.insert(out, "    },")
    for k, v in pairs(r) do
        if k ~= "class" and k ~= "title" then
            if type(v) == "string" then
                table.insert(out, string.format("    %s = \"%s\",", k, v))
            else
                table.insert(out, string.format("    %s = %s,", k, v and "true" or "false"))
            end
        end
    end
    table.insert(out, "})")
end
table.insert(out, "")

-- Layer rules
table.insert(out, "-- Layer rules")
local layer_rules = {
    {namespace = "hyprpicker", no_anim = true},
    {namespace = "selection", animation = "popin"},
    {namespace = "overlay", animation = "fade"},
}
for _, r in ipairs(layer_rules) do
    table.insert(out, "hl.layer_rule({")
    table.insert(out, "    match = {")
    table.insert(out, string.format("        namespace = \"%s\",", r.namespace))
    table.insert(out, "    },")
    for k, v in pairs(r) do
        if k ~= "namespace" then
            table.insert(out, string.format("    %s = \"%s\",", k, v))
        end
    end
    table.insert(out, "})")
end

print(table.concat(out, "\n"))
#!/usr/bin/env python3
"""
Generate AGS theme CSS variables from universal colors schema
Usage: python3 generate-ags-theme.py [colors-universal.json] [output.js]
"""

import json
import sys
import os

def load_colors(path=None):
    if path is None:
        path = os.path.join(os.path.dirname(__file__), "colors-universal.json")
    with open(path) as f:
        return json.load(f)

def hex_to_rgba(hex_color, alpha=1.0):
    hex_color = hex_color.lstrip("#")
    r = int(hex_color[0:2], 16)
    g = int(hex_color[2:4], 16)
    b = int(hex_color[4:6], 16)
    return f"rgba({r}, {g}, {b}, {alpha})"

def hex_to_alpha(hex_color, alpha):
    """Convert #RRGGBB + alpha to GTK alpha() function format"""
    return f"alpha({hex_color}, {alpha})"

def main():
    colors_path = sys.argv[1] if len(sys.argv) > 1 else None
    output_path = sys.argv[2] if len(sys.argv) > 2 else None
    
    c = load_colors(colors_path)
    base = c["base"]
    palette = c["palette"]
    semantic = c["semantic"]
    state = c["state"]
    alpha = c["alpha"]
    meta = c["metadata"]
    
    out = []
    out.append(f"// Generated by generate-ags-theme.py from colors-universal.json")
    out.append(f"// Palette: {meta.get('name', 'custom_dotfiles')}")
    out.append(f"// Variant: {meta.get('variant', 'dark')}")
    out.append("")
    
    # Base colors
    out.append("export const AGS_THEME = {")
    out.append("  // Base colors")
    out.append(f"  bg: '{base['bg']}',")
    out.append(f"  bgAlt: '{base['bg_alt']}',")
    out.append(f"  bgElevated: '{base['bg_elevated']}',")
    out.append(f"  bgOverlay: '{base['bg_overlay']}',")
    out.append(f"  fg: '{base['fg']}',")
    out.append(f"  fgMuted: '{base['fg_muted']}',")
    out.append(f"  fgSubtle: '{base['fg_subtle']}',")
    out.append(f"  border: '{base['border']}',")
    out.append(f"  borderFocus: '{base['border_focus']}',")
    out.append(f"  borderSubtle: '{base['border_subtle']}',")
    out.append("")
    
    # Palette (16 colors)
    out.append("  // ANSI 16-color palette")
    palette_names = [
        "black", "red", "green", "yellow", "blue", "magenta", "cyan", "orange",
        "brightBlack", "brightRed", "brightGreen", "brightYellow", "brightBlue", "brightMagenta", "brightCyan", "brightWhite"
    ]
    for i, name in enumerate(palette_names):
        if i < 8:
            key = list(palette.keys())[i]
        else:
            key = list(palette.keys())[i]
        out.append(f"  {name}: '{palette[key]}',")
    out.append("")
    
    # Semantic colors
    out.append("  // Semantic colors")
    for role, vals in semantic.items():
        out.append(f"  {role}: {{")
        for variant, hex_val in vals.items():
            out.append(f"    {variant}: '{hex_val}',")
        out.append("  },")
    out.append("")
    
    # State colors
    out.append("  // State colors")
    out.append("  state: {")
    for state_name, vals in state.items():
        out.append(f"    {state_name}: {{")
        for prop, val in vals.items():
            if isinstance(val, (int, float)):
                out.append(f"      {prop}: {val},")
            else:
                out.append(f"      {prop}: '{val}',")
        out.append("    },")
    out.append("  },")
    out.append("")
    
    # Alpha values
    out.append("  // Alpha values")
    out.append("  alpha: {")
    for name, val in alpha.items():
        out.append(f"    {name}: {val},")
    out.append("  },")
    out.append("")
    
    # Typography
    typo = c["typography"]
    out.append("  // Typography")
    out.append("  typography: {")
    for k, v in typo.items():
        if isinstance(v, (int, float)):
            out.append(f"    {k}: {v},")
        else:
            out.append(f"    {k}: '{v}',")
    out.append("  },")
    out.append("")
    
    # Spacing
    spacing = c["spacing"]
    out.append("  // Spacing")
    out.append("  spacing: {")
    for k, v in spacing.items():
        out.append(f"    {k}: {v},")
    out.append("  },")
    out.append("")
    
    # Hyprland sync (these come from hyprctl at runtime)
    out.append("  // Hyprland values (synced at runtime from hyprctl)")
    out.append("  hyprland: {")
    out.append("    activeOpacity: 0.9,")
    out.append("    inactiveOpacity: 0.9,")
    out.append("    rounding: 10,")
    out.append("    borderSize: 2,")
    out.append("    gapsOut: 10,")
    out.append("    activeBorder: '0xF8F8F2',")
    out.append("    inactiveBorder: '0x7A7A7A',")
    out.append("  },")
    out.append("")
    
    out.append("  // Metadata")
    out.append(f"  name: '{meta.get('name', 'custom_dotfiles')}',")
    out.append(f"  variant: '{meta.get('variant', 'dark')}',")
    out.append("};")
    out.append("")
    
    # Helper functions for CSS generation
    out.append("// CSS variable generators")
    out.append("export function toDefineColor(name, value) {")
    out.append("  return `@define-color ${name} ${value};`;")
    out.append("}")
    out.append("")
    out.append("export function alpha(color, a) {")
    out.append("  return `alpha(${color}, ${a})`;")
    out.append("}")
    out.append("")
    out.append("export function rgba(color, a) {")
    out.append("  // Convert hex to rgba")
    out.append("  const hex = color.replace('#', '');")
    out.append("  const r = parseInt(hex.slice(0, 2), 16);")
    out.append("  const g = parseInt(hex.slice(2, 4), 16);")
    out.append("  const b = parseInt(hex.slice(4, 6), 16);")
    out.append("  return `rgba(${r}, ${g}, ${b}, ${a})`;")
    out.append("}")
    
    result = "\n".join(out)
    
    if output_path:
        with open(output_path, "w") as f:
            f.write(result)
        print(f"Written to {output_path}", file=sys.stderr)
    else:
        print(result)

if __name__ == "__main__":
    main()
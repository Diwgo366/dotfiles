#!/usr/bin/env python3
"""
Generate hyprland-gui.lua from universal colors schema
Usage: python3 generate-hyprland.py [colors-universal.json] [output.lua]
"""

import json
import sys
import os

def load_colors(path=None):
    if path is None:
        path = os.path.join(os.path.dirname(__file__), "colors-universal.json")
    with open(path) as f:
        return json.load(f)

def hex_to_hypr(hex_color, alpha=None):
    hex_color = hex_color.lstrip("#")
    if alpha is not None:
        a = int(round(alpha * 255))
        return f"0x{a:02x}{hex_color.upper()}"
    return "0x" + hex_color.upper()

def main():
    colors_path = sys.argv[1] if len(sys.argv) > 1 else None
    output_path = sys.argv[2] if len(sys.argv) > 2 else None
    
    c = load_colors(colors_path)
    base = c["base"]
    palette = c["palette"]
    hypr = c["hyprland"]
    alpha = c["alpha"]
    meta = c["metadata"]
    
    # Override from env vars
    rounding = int(os.getenv("HYPR_ROUNDING", hypr["rounding"]))
    gaps_out = int(os.getenv("HYPR_GAPS_OUT", hypr["gaps_out"]))
    border_size = int(os.getenv("HYPR_BORDER_SIZE", hypr["border_size"]))
    active_opacity = float(os.getenv("HYPR_ACTIVE_OPACITY", hypr["active_opacity"]))
    inactive_opacity = float(os.getenv("HYPR_INACTIVE_OPACITY", hypr["inactive_opacity"]))
    blur_enabled = os.getenv("HYPR_BLUR_ENABLED", str(hypr["blur"]["enabled"]).lower()) == "true"
    shadow_enabled = os.getenv("HYPR_SHADOW_ENABLED", str(hypr["shadow"]["enabled"]).lower()) == "true"
    
    # Colors
    active_border = hex_to_hypr(base["border_focus"])
    inactive_border = hex_to_hypr(palette["bright_black"])
    bg_color = hex_to_hypr(base["bg"], active_opacity)
    shadow_color = hex_to_hypr("1a1a1a", alpha["shadow"])
    
    out = []
    out.append(f"-- Generated by generate-hyprland.py from colors-universal.json")
    out.append(f"-- Palette: {meta.get('name', 'custom_dotfiles')}")
    out.append("")
    out.append("-- Environment")
    out.append('hl.env("XCURSOR_THEME", "Future-cyan-cursors")')
    out.append('hl.env("XCURSOR_SIZE", "24")')
    out.append("")
    out.append("-- Settings")
    out.append("hl.config({")
    out.append("    animations = {")
    out.append("        enabled = true,")
    out.append("    },")
    out.append("    decoration = {")
    out.append(f"        active_opacity = {active_opacity},")
    out.append("        blur = {")
    out.append("            contrast = 0.9,")
    out.append(f"            enabled = {str(blur_enabled).lower()},")
    out.append("            ignore_opacity = false,")
    out.append("            new_optimizations = true,")
    out.append("            noise = 0.015,")
    out.append("            passes = 1,")
    out.append("            size = 1,")
    out.append("            vibrancy = 0.1,")
    out.append("        },")
    out.append(f"        inactive_opacity = {inactive_opacity},")
    out.append(f"        rounding = {rounding},")
    out.append("        shadow = {")
    out.append(f"            color = \"{shadow_color}\",")
    out.append(f"            color_inactive = \"{shadow_color}\",")
    out.append(f"            enabled = {str(shadow_enabled).lower()},")
    out.append("            range = 3,")
    out.append("            render_power = 2,")
    out.append("        },")
    out.append("    },")
    out.append("    general = {")
    out.append(f"        border_size = {border_size},")
    out.append("        col = {")
    out.append(f"            active_border = \"{active_border}\",")
    out.append(f"            inactive_border = \"{inactive_border}\",")
    out.append("        },")
    out.append(f"        gaps_out = {gaps_out},")
    out.append("        layout = \"master\",")
    out.append("    },")
    out.append("    input = {")
    out.append("        sensitivity = 1.0,")
    out.append("    },")
    out.append("    master = {")
    out.append("        mfact = 0.5,")
    out.append("        new_status = \"slave\",")
    out.append("    },")
    out.append("})")
    out.append("")
    
    # Animations
    anims = [
        {"leaf": "global", "enabled": False},
        {"leaf": "windowsIn", "enabled": True, "speed": 8.0, "bezier": "default", "style": "popin"},
        {"leaf": "windowsOut", "enabled": True, "speed": 8.0, "bezier": "default", "style": "popin"},
        {"leaf": "windowsMove", "enabled": True, "speed": 8.0, "bezier": "default"},
        {"leaf": "layersIn", "enabled": True, "speed": 8.0, "bezier": "default", "style": "slide top"},
        {"leaf": "layersOut", "enabled": True, "speed": 8.0, "bezier": "default", "style": "slide top"},
        {"leaf": "fade", "enabled": True, "speed": 1.0, "bezier": "default"},
        {"leaf": "fadeIn", "enabled": True, "speed": 8.0, "bezier": "default"},
        {"leaf": "fadeOut", "enabled": True, "speed": 8.0, "bezier": "default"},
        {"leaf": "fadeLayersIn", "enabled": True, "speed": 8.0, "bezier": "default"},
        {"leaf": "fadeLayersOut", "enabled": True, "speed": 8.0, "bezier": "default"},
        {"leaf": "border", "enabled": True, "speed": 10.0, "bezier": "default"},
        {"leaf": "borderangle", "enabled": True, "speed": 1.0, "bezier": "default"},
        {"leaf": "workspaces", "enabled": True, "speed": 6.0, "bezier": "default", "style": "slide"},
        {"leaf": "zoomFactor", "enabled": False},
        {"leaf": "monitorAdded", "enabled": True, "speed": 1.0, "bezier": "default"},
    ]
    
    out.append("-- Animations")
    for a in anims:
        out.append("hl.animation({")
        out.append(f"    leaf = \"{a['leaf']}\",")
        out.append(f"    enabled = {str(a['enabled']).lower()},")
        if "speed" in a: out.append(f"    speed = {a['speed']},")
        if "bezier" in a: out.append(f"    bezier = \"{a['bezier']}\",")
        if "style" in a: out.append(f"    style = \"{a['style']}\",")
        out.append("})")
    out.append("")
    
    # Window rules (Lua strings need double backslash for regex)
    window_rules = [
        {"class": "^(wofi)$", "stay_focused": True},
        {"class": "^(wofi)$", "suppress_event": "change_focused"},
        {"class": "^$", "no_blur": True},
        {"class": "^(xdg\\\\-desktop\\\\-portal\\\\-gtk|xarchiver)$", "center": True, "float": True, "size": "[700, 500]"},
        {"class": "^(Zotero|file\\\\-png)$", "center": True, "size": "700 500"},
        {"title": "^(Pantalla\\\\ en\\\\ pantalla)$", "opaque": True},
        {"class": "^(google\\\\-chrome)$", "opaque": True},
        {"class": "^(org\\\\.gnome\\\\.gThumb)$", "opaque": True},
        {"title": "^(Imagen\\\\ en\\\\ imagen)$", "opaque": True},
        {"class": "^(brave\\\\-origin)$", "opaque": True},
    ]
    
    out.append("-- Window rules")
    for r in window_rules:
        out.append("hl.window_rule({")
        out.append("    match = {")
        if "class" in r: out.append(f"        class = \"{r['class']}\",")
        if "title" in r: out.append(f"        title = \"{r['title']}\",")
        out.append("    },")
        for k, v in r.items():
            if k not in ("class", "title"):
                if isinstance(v, bool):
                    out.append(f"    {k} = {str(v).lower()},")
                elif isinstance(v, str):
                    out.append(f"    {k} = \"{v}\",")
                else:
                    out.append(f"    {k} = {str(v).lower()},")
        out.append("})")
    out.append("")
    
    # Layer rules
    layer_rules = [
        {"namespace": "hyprpicker", "no_anim": True},
        {"namespace": "selection", "animation": "popin"},
        {"namespace": "overlay", "animation": "fade"},
    ]
    
    out.append("-- Layer rules")
    for r in layer_rules:
        out.append("hl.layer_rule({")
        out.append("    match = {")
        out.append(f"        namespace = \"{r['namespace']}\",")
        out.append("    },")
        for k, v in r.items():
            if k != "namespace":
                if isinstance(v, bool):
                    out.append(f"    {k} = {str(v).lower()},")
                else:
                    out.append(f"    {k} = \"{v}\",")
        out.append("})")
    
    result = "\n".join(out)
    
    if output_path:
        with open(output_path, "w") as f:
            f.write(result)
        print(f"Written to {output_path}", file=sys.stderr)
    else:
        print(result)

if __name__ == "__main__":
    main()